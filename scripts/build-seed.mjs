// Regenerate vercel-deploy/data.js, the built-in fallback the site uses when /api/promos is unavailable
// (e.g. a plain local static server).
//   node scripts/build-seed.mjs                 → fetch the live page
//   node scripts/build-seed.mjs saved-page.html → parse a saved copy
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { fetchPage, parsePage, fingerprint } from '../vercel-deploy/lib/sia.js';

const file = process.argv[2];
const html = file ? readFileSync(file, 'utf8') : await fetchPage();
const retrieved = process.env.RETRIEVED || new Date().toISOString();
const promo = parsePage(html, { retrieved });
promo.hash = await fingerprint(promo);
const { warnings, ...seed } = promo;
for (const w of warnings) console.warn('warning:', w);

const out = fileURLToPath(new URL('../vercel-deploy/data.js', import.meta.url));
writeFileSync(out, `// Built-in fallback data, generated by scripts/build-seed.mjs. Source: ${promo.meta.source}\n`
  + `window.PROMO_SEED = ${JSON.stringify(seed).replace(/\},\{/g, '},\n{')};\n`);
console.log(`wrote ${out}: ${promo.id}, ${promo.routes.length} deals`);
